"""Generate an independent SIN12 map; never overwrite the SIN9/SIN11 map."""
from pathlib import Path
import json
from scripts.build_nav_map import occupied_cells, shortest_path_from

ROOT = Path(__file__).resolve().parents[1]


def build():
    original = json.loads((ROOT / 'config/nav-map-2m.json').read_text(encoding='utf-8'))
    geometry = json.loads((ROOT / 'config/robot-geometry.json').read_text(encoding='utf-8'))
    # 149 mm corner radius + 50 mm design clearance + grid-edge allowance.
    # Keep all four original positions. Reduce physical obstacles, never the
    # robot clearance, so the connected test area remains useful after inflation.
    obstacles = [{**obstacle, 'size_cells': [1, 2] if obstacle['id'] == 'A' else [1, 1]}
                 for obstacle in original['obstacles']]
    spec = {**original, 'map_id': 0x2613, 'name': 'SIN12 四障碍宽通道地图 R1',
            'robot_width_m': geometry['body_width_mm'] / 1000,
            'robot_length_m': geometry['body_length_mm'] / 1000,
            'inflation_radius_m': .21, 'start_cell': [17, 2], 'example_goal_cell': [10, 17],
            'obstacles': obstacles}
    cells = occupied_cells(spec)
    route = shortest_path_from(spec, cells, tuple(spec['start_cell']), tuple(spec['example_goal_cell']))
    if not route:
        raise ValueError('SIN12 example route is blocked')
    reachable = sum(bool(shortest_path_from(spec, cells, tuple(spec['start_cell']), (x, y)))
                    for y in range(20) for x in range(20))
    if reachable < 160:
        raise ValueError('Sparse map must keep at least 160 start-connected cells')
    bits = sum(value << index for index, value in enumerate(cells))
    (ROOT / 'config/nav-map-sin12.json').write_text(json.dumps(spec, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    (ROOT / 'fpga/nav/sin12_map.vh').write_text(
        '// Generated by python -m scripts.build_sin12_map\n'
        f"`define SIN12_MAP_ID 16'h{spec['map_id']:04X}\n"
        f"`define SIN12_MAP_BITS 400'h{bits:0100X}\n", encoding='ascii')
    (ROOT / 'output/board/sin12_map_audit.json').write_text(json.dumps(
        {'map_id': f"0x{spec['map_id']:04X}", 'occupied': sum(cells),
         'free': len(cells)-sum(cells), 'reachable': reachable, 'example_steps': len(route)-1,
         'body_mm': [200, 220], 'map_bits': f'{bits:0100X}',
         'original_map_unchanged': True}, indent=2)+'\n', encoding='utf-8')
    print(f"SIN12 map 0x{spec['map_id']:04X}: occupied={sum(cells)}, reachable={reachable}, example_steps={len(route)-1}")


if __name__ == '__main__':
    build()
